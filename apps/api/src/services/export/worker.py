def _create_document_template(
    title: str,
    content: str,
    document_info: dict[str, Any],
    citations: list[dict[str, Any]] | None = None,
    language: str | None = None,
) -> Any:
    """Create a DOCX document with tender response formatting.

    Args:
        title: Document title
        content: Response content
        document_info: Document metadata
        citations: Optional citation list
        language: Language code (fr, en, es, de)

    Returns:
        Document object
    """
    docx = _load_docx_module()
    docx_shared = _load_docx_shared()
    docx_enum = _load_docx_enum()

    Document = getattr(docx, "Document")
    Inches = getattr(docx_shared, "Inches")
    Pt = getattr(docx_shared, "Pt")
    RGBColor = getattr(docx_shared, "RGBColor")
    WD_ALIGN_PARAGRAPH = getattr(docx_enum.text, "WD_ALIGN_PARAGRAPH")

    texts = _get_language_texts(language)

    doc = Document()

    style = doc.styles["Normal"]
    font = style.font
    font.name = "Arial"
    font.size = Pt(11)

    header = doc.add_heading(texts["title"], level=0)
    header.alignment = WD_ALIGN_PARAGRAPH.CENTER

    title_para = doc.add_heading(title, level=1)
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

    table = doc.add_table(rows=4, cols=2)
    table.style = "Table Grid"

    metadata_rows = [
        (texts["document_label"], document_info.get("filename", texts["na"])),
        (texts["date_label"], document_info.get("created_at", texts["na"])),
        (texts["status_label"], document_info.get("status", texts["na"])),
        (texts["reference_label"], document_info.get("id", texts["na"])[:8]),
    ]

    for i, (key, value) in enumerate(metadata_rows):
        row = table.rows[i]
        row.cells[0].text = key
        row.cells[1].text = value

    doc.add_paragraph()

    doc.add_heading(texts["section"], level=2)

    paragraphs = content.split("\n\n")
    for para in paragraphs:
        if para.strip():
            if para.strip().startswith("##"):
                heading_text = para.strip().lstrip("#").strip()
                doc.add_heading(heading_text, level=2)
            elif para.strip().startswith("#"):
                heading_text = para.strip().lstrip("#").strip()
                doc.add_heading(heading_text, level=1)
            else:
                p = doc.add_paragraph(para.strip())
                p.paragraph_format.space_after = Pt(12)

    if citations:
        doc.add_page_break()
        doc.add_heading(texts["citations"], level=2)

        for i, citation in enumerate(citations[:20], 1):
            p = doc.add_paragraph()
            p.add_run(f"[{i}] ").bold = True
            p.add_run(f"Position {citation.get('position', texts['na'])}: ")
            citation_content = str(citation.get("content", texts["na"]))[:200]
            p.add_run(citation_content)
            if len(str(citation.get("content", ""))) > 200:
                p.add_run("...")

    section = doc.sections[0]
    footer = section.footer
    footer_para = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    footer_para.text = texts["footer"]
    footer_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

    return doc


def export_to_docx(
    response_id: str,
    output_path: Path | None = None,
    tenant_id: str | None = None,
) -> tuple[Path, str]:
    """Export a response to DOCX format.

    Args:
        response_id: The response ID to export
        output_path: Optional custom output path
        tenant_id: Tenant ID for validation

    Returns:
        Tuple[path to exported file, export_id]
    """
    response = document_repository.get_response(response_id)
    if response is None:
        raise RuntimeError(f"Response not found: {response_id}")

    document_id = response["document_id"]

    from importlib import import_module

    supabase_module = import_module("supabase")
    from ...core.supabase_client import get_supabase_settings

    settings = get_supabase_settings()
    client = supabase_module.create_client(settings.url, settings.service_role_key)

    doc_result = (
        client.table("documents")
        .select("*")
        .eq("id", document_id)
        .maybe_single()
        .execute()
    )
    doc_data = getattr(doc_result, "data", None)

    citations_data_raw = response.get("citations")
    citations_data: dict[str, object] | None = (
        citations_data_raw if isinstance(citations_data_raw, dict) else None
    )
    citations: list[dict[str, Any]] = []
    language: str | None = None

    if citations_data is not None:
        raw_citations = citations_data.get("citations", [])
        if isinstance(raw_citations, list):
            citations = [
                cast(dict[str, Any], item)
                for item in raw_citations
                if isinstance(item, dict)
            ]
        language_raw = citations_data.get("language")
        if isinstance(language_raw, str):
            language = language_raw

    texts = _get_language_texts(language)

    document_info = {
        "id": document_id,
        "filename": doc_data.get("filename", "document.pdf")
        if doc_data
        else "document.pdf",
        "created_at": response["created_at"],
        "status": texts["completed"],
    }

    if tenant_id is None and isinstance(doc_data, dict):
        tenant_raw = doc_data.get("tenant_id")
        if isinstance(tenant_raw, str):
            tenant_id = tenant_raw

    export_record = document_repository.create_export(
        document_id=document_id,
        response_id=response_id,
        format="docx",
        file_path="",
        tenant_id=tenant_id or "00000000-0000-0000-0000-000000000001",
    )

    if output_path is None:
        output_path = get_export_storage_path(export_record["id"], ".docx")

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    doc = _create_document_template(
        title=texts["title"],
        content=response["content"],
        document_info=document_info,
        citations=citations,
        language=language,
    )

    doc.save(str(output_path))

    document_repository.update_export_status(
        export_id=export_record["id"],
        status="completed",
        file_path=str(output_path),
    )

    logger.info(
        "Exported response %s to DOCX: %s",
        response_id,
        output_path,
    )

    return output_path, export_record["id"]


def process_export_request(event_payload: dict[str, Any]) -> None:
    """Process export request event from RabbitMQ."""
    payload = event_payload.get("payload", event_payload)
    response_id = str(payload.get("response_id", ""))
    format_type = str(payload.get("format", "docx"))
    tenant_id = str(payload.get("tenant_id", ""))

    if not response_id:
        raise RuntimeError("export_requested event missing response_id")

    logger.info(
        "Processing export request for response_id=%s, format=%s",
        response_id,
        format_type,
    )

    try:
        if format_type == "docx":
            file_path, export_id = export_to_docx(response_id, tenant_id=tenant_id or None)
        else:
            raise RuntimeError(f"Unsupported export format: {format_type}")

        response = document_repository.get_response(response_id)
        if response:
            completion_event = build_event(
                EVENT_EXPORT_COMPLETE,
                {
                    "response_id": response_id,
                    "export_id": export_id,
                    "document_id": response["document_id"],
                    "tenant_id": tenant_id,
                    "format": format_type,
                    "file_path": str(file_path),
                    "status": "completed",
                },
            )
            publish_event(EVENT_EXPORT_COMPLETE, completion_event)

        logger.info("Export complete for response_id=%s", response_id)

    except Exception as error:
        logger.exception("Export failed for response_id=%s", response_id)
        raise


def run_export_worker() -> None:
    """Start the export worker consuming from export queue."""
    from ...core.pipeline_events import QUEUE_EXPORT

    logger.info("Starting export worker on queue: %s", QUEUE_EXPORT)
    consume(QUEUE_EXPORT, process_export_request)
